#!/usr/bin/env bash
# Shared functions and constants for the dev scripts. `source`d by other scripts.
set -euo pipefail

DEV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCAL_DIR="$DEV_DIR/.local"          # git-ignored: holds randomly generated passwords and connection strings
CLUSTER_NAME="shp-local"
NAMESPACE="shp-deps"
CTX="kind-${CLUSTER_NAME}"
# shellcheck disable=SC2034  # used in deploy.sh
TEMPLATES_GIT="${SHP_TEMPLATES_GIT:-https://github.com/viethung12062005/shp-platform-templates.git}"
# shellcheck disable=SC2034
TEMPLATES_REF="${SHP_TEMPLATES_REF:-v0.1.5}"

# Tools installed by install-tools.sh (dev/.local/bin) take precedence; no need to change the machine PATH.
PATH="$DEV_DIR/.local/bin:$PATH"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

need() { command -v "$1" >/dev/null 2>&1 || die "Missing '$1'. $2"; }
k()    { kubectl --context "$CTX" "$@"; }

rand_hex() { openssl rand -hex 16; }

# Generate random passwords the first time; keep them afterwards so data in the cluster keeps working.
ensure_credentials() {
  mkdir -p "$LOCAL_DIR"
  local f="$LOCAL_DIR/credentials.env"
  if [ ! -f "$f" ]; then
    ( umask 077
      {
        echo "POSTGRES_PASSWORD=$(rand_hex)"
        echo "REDIS_PASSWORD=$(rand_hex)"
        echo "RABBITMQ_PASSWORD=$(rand_hex)"
        echo "KEYCLOAK_ADMIN_PASSWORD=$(rand_hex)"
      } > "$f" )
    log "Generated random passwords into $f (do not commit this file)"
  fi
  # Add missing keys to a file generated by an older version.
  grep -q '^AZURITE_ACCOUNT_KEY=' "$f" || echo "AZURITE_ACCOUNT_KEY=$(openssl rand -base64 64 | tr -d '\n')" >> "$f"
  grep -q '^GRAFANA_ADMIN_PASSWORD=' "$f" || echo "GRAFANA_ADMIN_PASSWORD=$(rand_hex)" >> "$f"
  # shellcheck disable=SC1090
  . "$f"
}

apply_credentials_secret() {
  k -n "$NAMESPACE" create secret generic shp-local-credentials \
    --from-literal=postgres-password="$POSTGRES_PASSWORD" \
    --from-literal=redis-password="$REDIS_PASSWORD" \
    --from-literal=rabbitmq-password="$RABBITMQ_PASSWORD" \
    --from-literal=keycloak-admin-password="$KEYCLOAK_ADMIN_PASSWORD" \
    --from-literal=azurite-accounts="shp:$AZURITE_ACCOUNT_KEY" \
    --from-literal=grafana-admin-password="$GRAFANA_ADMIN_PASSWORD" \
    --dry-run=client -o yaml | k apply -f - >/dev/null
}
